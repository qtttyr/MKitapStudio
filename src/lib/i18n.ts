export type MessageKey = keyof typeof dict.en

type LangCtx = { lang: Lang; setLang: (l: Lang) => void; t: (k: MessageKey) => string }

export const LangContext = createContext<LangCtx>({ lang: 'en', setLang: () => {}, t: (k) => dict.en[k] })

export function useI18n() {
  return useContext(LangContext)
}

const LANG_KEY = 'mkstudio.lang'

export function loadLang(): Lang {
  const saved = localStorage.getItem(LANG_KEY)
  if (saved === 'ru' || saved === 'en') return saved
  return 'en'
}
